import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ensurePrivateDir, writeFileAtomic, writeJsonAtomic } from './secure-fs.js';
import { encryptJson, VAULT_AAD } from './extension/lib/vault-crypto.js';

const EXTENSION_SOURCE_DIR = fileURLToPath(new URL('./extension/', import.meta.url));
const EXTENSION_VAULT_VERSION = 1;

// 生成物にコピーする拡張機能のソース（src/extension/ からの相対パス）
export const EXTENSION_FILES = Object.freeze([
  'background.js',
  'popup.html',
  'popup.js',
  'popup.css',
  'lib/vault-crypto.js',
  'lib/rules.js',
  'lib/unlocker.js',
]);

// 旧バージョンが出力していた平文のファイル
const LEGACY_FILES = ['rules.json'];

function enabledEntries(entries) {
  return entries.filter((entry) => entry.enabled);
}

function buildHostPermissions(entries) {
  const permissions = enabledEntries(entries).flatMap(({ domain, includeSubdomains }) => (
    includeSubdomains ? [`*://${domain}/*`, `*://*.${domain}/*`] : [`*://${domain}/*`]
  ));
  return [...new Set(permissions)];
}

export function formatExtensionVersion(counter) {
  return `1.0.${counter}`;
}

export function buildManifest(entries, counter) {
  return {
    manifest_version: 3,
    name: 'Edge Basic Auth (generated)',
    version: formatExtensionVersion(counter),
    description: 'Generated by edge-basic-auth. Do not edit by hand.',
    permissions: ['declarativeNetRequest', 'storage'],
    host_permissions: buildHostPermissions(entries),
    background: { service_worker: 'background.js', type: 'module' },
    action: { default_popup: 'popup.html', default_title: 'Edge Basic Auth' },
  };
}

/**
 * 拡張機能に渡すのは、有効なエントリのルール生成に必要な項目だけにする。
 */
export function selectExtensionEntries(entries) {
  return enabledEntries(entries).map(({ domain, includeSubdomains, username, password }) => (
    { domain, includeSubdomains, username, password }
  ));
}

export async function buildExtensionVault(entries, key, kdf) {
  const sealed = await encryptJson(key, { entries: selectExtensionEntries(entries) }, VAULT_AAD.extension);
  return { version: EXTENSION_VAULT_VERSION, kdf, ...sealed };
}

function copyExtensionSources(extensionDir) {
  for (const file of EXTENSION_FILES) {
    const destination = path.join(extensionDir, file);
    ensurePrivateDir(path.dirname(destination));
    writeFileAtomic(destination, fs.readFileSync(path.join(EXTENSION_SOURCE_DIR, file)));
  }
}

function removeLegacyFiles(extensionDir) {
  for (const file of LEGACY_FILES) fs.rmSync(path.join(extensionDir, file), { force: true });
}

export function writeExtension(extensionDir, { manifest, vault }) {
  ensurePrivateDir(extensionDir);
  copyExtensionSources(extensionDir);
  writeJsonAtomic(path.join(extensionDir, 'vault.json'), vault);
  removeLegacyFiles(extensionDir);
  // manifest (version) の更新を最後にする
  writeJsonAtomic(path.join(extensionDir, 'manifest.json'), manifest);
}
