import { describe, test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  buildManifest,
  selectExtensionEntries,
  buildExtensionVault,
  writeExtension,
  EXTENSION_FILES,
} from '../src/generate.js';
import {
  createKdfParams,
  deriveKey,
  decryptJson,
  VAULT_AAD,
} from '../src/extension/lib/vault-crypto.js';

const baseEntry = {
  id: '00000000-0000-0000-0000-000000000001',
  label: '社内ダッシュボード',
  domain: 'dashboard.example.com',
  includeSubdomains: false,
  username: 'user',
  password: 'pass',
  enabled: true,
};

function makeTempDir() {
  return fs.mkdtempSync(path.join(os.tmpdir(), 'eba-gen-'));
}

describe('buildManifest', () => {
  test('ポップアップと service worker を持つ Manifest V3 を生成する', () => {
    assert.deepEqual(buildManifest([baseEntry], 12), {
      manifest_version: 3,
      name: 'Edge Basic Auth (generated)',
      version: '1.0.12',
      description: 'Generated by edge-basic-auth. Do not edit by hand.',
      permissions: ['declarativeNetRequest', 'storage'],
      host_permissions: ['*://dashboard.example.com/*'],
      background: { service_worker: 'background.js', type: 'module' },
      action: { default_popup: 'popup.html', default_title: 'Edge Basic Auth' },
    });
  });

  test('includeSubdomains が true なら *.<domain> も host_permissions に加える', () => {
    const manifest = buildManifest([{ ...baseEntry, includeSubdomains: true }], 1);
    assert.deepEqual(manifest.host_permissions, [
      '*://dashboard.example.com/*',
      '*://*.dashboard.example.com/*',
    ]);
  });

  test('無効なエントリは host_permissions に含めない', () => {
    assert.deepEqual(buildManifest([{ ...baseEntry, enabled: false }], 1).host_permissions, []);
  });
});

describe('selectExtensionEntries', () => {
  test('有効なエントリだけを、ルール生成に必要な項目に絞って返す', () => {
    const selected = selectExtensionEntries([
      baseEntry,
      { ...baseEntry, domain: 'disabled.example.com', enabled: false },
    ]);
    assert.deepEqual(selected, [{
      domain: 'dashboard.example.com',
      includeSubdomains: false,
      username: 'user',
      password: 'pass',
    }]);
  });
});

describe('buildExtensionVault', () => {
  test('拡張機能用の vault を同じ鍵で復号できる', async () => {
    const kdf = createKdfParams({ iterations: 1000 });
    const key = await deriveKey('master password!!', kdf);
    const vault = await buildExtensionVault([baseEntry], key, kdf);

    assert.equal(vault.version, 1);
    assert.deepEqual(vault.kdf, kdf);
    assert.ok(!JSON.stringify(vault).includes('dashboard.example.com'));
    const decrypted = await decryptJson(key, vault, VAULT_AAD.extension);
    assert.deepEqual(decrypted, { entries: selectExtensionEntries([baseEntry]) });
  });
});

describe('writeExtension', () => {
  const manifest = buildManifest([], 1);
  const vault = { version: 1, kdf: {}, iv: 'aXY=', ciphertext: 'Y3Q=' };

  test('manifest・vault・拡張機能のソース一式を書き出す', () => {
    const extensionDir = path.join(makeTempDir(), 'extension');
    writeExtension(extensionDir, { manifest, vault });

    const readJson = (name) => JSON.parse(fs.readFileSync(path.join(extensionDir, name), 'utf8'));
    assert.deepEqual(readJson('manifest.json'), manifest);
    assert.deepEqual(readJson('vault.json'), vault);
    for (const file of EXTENSION_FILES) {
      assert.ok(fs.existsSync(path.join(extensionDir, file)), file);
    }
  });

  test('旧形式の平文 rules.json を削除する', () => {
    const extensionDir = path.join(makeTempDir(), 'extension');
    fs.mkdirSync(extensionDir);
    fs.writeFileSync(path.join(extensionDir, 'rules.json'), '[]');
    writeExtension(extensionDir, { manifest, vault });
    assert.equal(fs.existsSync(path.join(extensionDir, 'rules.json')), false);
  });

  test('POSIX 環境ではディレクトリを 0700、ファイルを 0600 にする', { skip: process.platform === 'win32' }, () => {
    const extensionDir = path.join(makeTempDir(), 'extension');
    writeExtension(extensionDir, { manifest, vault });

    const mode = (p) => fs.statSync(p).mode & 0o777;
    assert.equal(mode(extensionDir), 0o700);
    assert.equal(mode(path.join(extensionDir, 'lib')), 0o700);
    assert.equal(mode(path.join(extensionDir, 'vault.json')), 0o600);
    assert.equal(mode(path.join(extensionDir, 'lib', 'vault-crypto.js')), 0o600);
  });
});
